"""Bake the Stream Deck key font into font.rs (metrics) and font.bin (8-bit coverage).

Run by hand when the type scale changes; nothing here runs at build or run time.

    pip install pillow
    python engine/src/keyface/bake_font.py BarlowSemiCondensed-SemiBold.ttf

The source face is Barlow Semi Condensed SemiBold, (c) 2017 The Barlow Project Authors,
SIL Open Font License 1.1 (see OFL.txt next to this file). Labels are drawn in capitals,
so only the non-lowercase printable ASCII range and an ellipsis are baked.
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

# (Rust constant, pixel size), one per keyface::Scale step: a ratio of about 1.4 a step.
SIZES = [("SMALL", 16), ("MEDIUM", 20), ("LARGE", 32)]
CHARS = [chr(c) for c in range(0x20, 0x7F) if not chr(c).islower()] + ["…"]
PAD = 8


def bake(font_path):
    blob = bytearray()
    faces = []
    for name, size in SIZES:
        font = ImageFont.truetype(font_path, size)
        cap = font.getbbox("H", anchor="ls")
        cap_height = -cap[1]
        glyphs = []
        for ch in CHARS:
            image = Image.new("L", (size * 3, size * 3), 0)
            base = size * 2
            ImageDraw.Draw(image).text((PAD, base), ch, font=font, fill=255, anchor="ls")
            box = image.getbbox()
            advance = round(font.getlength(ch) * 4)
            if box is None:
                glyphs.append((ch, 0, 0, 0, 0, advance, len(blob)))
                continue
            crop = image.crop(box)
            glyphs.append((ch, box[0] - PAD, base - box[1], crop.width, crop.height, advance, len(blob)))
            blob.extend(crop.tobytes())
        faces.append((name, size, cap_height, round(cap_height * 1.5), glyphs))
    return faces, bytes(blob)


def main():
    here = pathlib.Path(__file__).parent
    faces, blob = bake(sys.argv[1])
    out = [
        "//! Generated by bake_font.py from Barlow Semi Condensed SemiBold (SIL OFL 1.1, see OFL.txt).",
        "//! Do not edit by hand; re-run the script instead.",
        "pub struct Glyph {",
        "    pub ch: char,",
        "    /// Offset of the bitmap's left edge from the pen, in pixels.",
        "    pub left: i8,",
        "    /// Rows the bitmap rises above the baseline.",
        "    pub top: i8,",
        "    pub width: u8,",
        "    pub height: u8,",
        "    /// Pen advance in quarter pixels.",
        "    pub advance: u8,",
        "    pub offset: u32,",
        "}",
        "pub struct Face {",
        "    pub cap_height: u8,",
        "    /// Baseline to baseline.",
        "    pub line_height: u8,",
        "    /// Sorted by `ch`.",
        "    pub glyphs: &'static [Glyph],",
        "}",
        'pub static COVERAGE: &[u8] = include_bytes!("font.bin");',
    ]
    for name, size, cap_height, line_height, glyphs in faces:
        out.append(f"/// {size} px.")
        out.append(f"pub static {name}: Face = Face {{")
        out.append(f"    cap_height: {cap_height},")
        out.append(f"    line_height: {line_height},")
        out.append("    glyphs: &[")
        for ch, left, top, width, height, advance, offset in sorted(glyphs):
            out.append(
                f"        Glyph {{ ch: '\\u{{{ord(ch):x}}}', left: {left}, top: {top}, width: {width}, "
                f"height: {height}, advance: {advance}, offset: {offset} }},"
            )
        out.append("    ],")
        out.append("};")
    (here / "font.rs").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    (here / "font.bin").write_bytes(blob)
    print(f"{len(blob)} coverage bytes")
    for name, size, cap_height, line_height, glyphs in faces:
        advance = {g[0]: g[5] for g in glyphs}
        samples = sys.argv[2:] or ["#888", "BLACKOUT", "KALEIDOSCO"]
        widths = ", ".join(f"{s}={sum(advance[c] for c in s) / 4:.1f}" for s in samples)
        print(f"{name} {size}px cap {cap_height} line {line_height}: {widths}")


if __name__ == "__main__":
    main()
